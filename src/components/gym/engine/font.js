export const GLYPH_W = 3;
export const GLYPH_H = 5;

export const textWidth = (text, spacing = 1) =>
  text.length ? text.length * (GLYPH_W + spacing) - spacing : 0;

export function drawText(ctx, text, x, y, color, { spacing = 1, scale = 1 } = {}) {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  for (const ch of String(text).toUpperCase()) {
    const glyph = GLYPHS[ch] || GLYPHS['?'];
    for (let row = 0; row < GLYPH_H; row++) {
      for (let col = 0; col < GLYPH_W; col++) {
        if (glyph[row][col] === '#') {
          ctx.fillRect(cx + col * scale, Math.round(y) + row * scale, scale, scale);
        }
      }
    }
    cx += (GLYPH_W + spacing) * scale;
  }
  return cx;
}
