export default function BadgeIcon({ group, earned, size = 24 }) {
  const rows = ICONS[group] || ICONS.core;
  const color = earned ? GROUPS[group].color : '#2b2f3a';
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      aria-hidden="true"
      className="gym-badge-icon"
    >
      {rows.flatMap((row, y) =>
        [...row].map((c, x) =>
          c === '#' ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill={color} /> : null
        )
      )}
    </svg>
  );
}
